def _games(rng: np.random.Generator) -> pd.DataFrame:
    n_casino = 150
    providers = [f"PRV{k}" for k in range(1, 9)]
    fee = dict(zip(providers, np.round(rng.uniform(0.08, 0.16, len(providers)), 3), strict=True))
    prov = rng.choice(providers, n_casino)
    casino = pd.DataFrame(
        {
            "game_id": [f"CAS{k:03d}" for k in range(n_casino)],
            "vertical": "casino",
            "provider_id": prov,
            "provider_fee_rate": [fee[p] for p in prov],
        }
    )
    sports = pd.DataFrame(
        {
            "game_id": [
                "SB_FOOTBALL",
                "SB_TENNIS",
                "SB_BASKETBALL",
                "SB_ESPORTS",
                "SB_HOCKEY",
                "SB_OTHER",
            ],
            "vertical": "sports",
            "provider_id": "SPORTSBOOK",
            "provider_fee_rate": 0.0,
        }
    )
    return pd.concat([casino, sports], ignore_index=True)


def _legit_life(
    i,
    ftd_s,
    prof,
    rng,
    obs_end_s,
    method,
    payfp,
    casino_games,
    casino_pop,
    sports_games,
    dep_rows,
    bet_rows,
    wd_rows,
    cb_rows,
    bonus_rows,
) -> float:
    v = rng.lognormal(0, 0.8)
    if rng.random() < prof.vip_share:
        v *= 8
    dep_scale = prof.base_deposit * v
    main_casino = rng.random() < prof.casino_share
    k = int(rng.integers(2, 9))
    fav_c = rng.choice(casino_games, k, p=casino_pop)
    fav_s = rng.choice(sports_games, min(k, len(sports_games)), replace=False)
    ftd_day = np.floor(ftd_s / DAY_S)
    last = ftd_s
    ftd_amt = 0.0
    one_and_done = rng.random() < 0.38
    m = 0
    while True:
        t0 = ftd_day + 30 * m
        if t0 * DAY_S > obs_end_s:
            break
        n_act = (
            max(1, rng.poisson(prof.days_per_month)) if m == 0 else rng.poisson(prof.days_per_month)
        )
        offs = np.unique(rng.integers(0, 30, n_act))
        if m == 0 and one_and_done:
            offs = np.unique(rng.integers(0, 3, int(rng.integers(0, 3))))
        if m == 0:
            offs = np.unique(np.concatenate([[0], offs]))
        days = t0 + offs
        days = days[days * DAY_S <= obs_end_s]
        month_dep = 0.0
        for j, day in enumerate(days):
            first = m == 0 and j == 0
            if first:
                dep = max(10.0, round(rng.lognormal(np.log(dep_scale), 0.5), 2))
                dep_s = ftd_s
                ftd_amt = dep
            else:
                dep = round(rng.lognormal(np.log(dep_scale), 0.6), 2)
                dep_s = day * DAY_S + rng.uniform(8, 23.5) * 3600
            month_dep += dep
            dep_rows.append((i, dep_s, dep, method, payfp, first))
            if rng.random() < 0.004:
                cb_rows.append((i, len(dep_rows) - 1, dep_s + rng.uniform(20, 75) * DAY_S, dep))
            casino = main_casino if rng.random() < 0.85 else not main_casino
            if casino:
                game = fav_c[rng.integers(0, len(fav_c))]
                stake = dep * 10 * rng.lognormal(0, 0.35)
                n_bets = 1 + rng.poisson(stake / 1.5)
                ggr = stake * 0.045 + stake * 1.2 / np.sqrt(n_bets) * rng.normal()
                if rng.random() < 0.0005:  # rare big win (jackpot / high-volatility hit)
                    ggr -= stake * rng.uniform(10, 40)
            else:
                game = fav_s[rng.integers(0, len(fav_s))]
                stake = dep * 4 * rng.lognormal(0, 0.35)
                n_bets = 1 + rng.poisson(stake / 10)
                ggr = stake * 0.06 + stake * 1.0 / np.sqrt(n_bets) * rng.normal()
            ggr = min(ggr, dep)
            bet_rows.append((i, day, game, int(n_bets), stake, ggr))
            last = max(last, dep_s)
            if ggr < 0 and rng.random() < 0.8:
                wd_s = day * DAY_S + rng.uniform(1, 23.9) * 3600
                wd_rows.append((i, wd_s, round(-ggr + dep * rng.uniform(0, 0.5), 2)))
                last = max(last, wd_s)
        if m == 0:
            if rng.random() < prof.welcome_optin:
                boost = (
                    1.5 if prof is KIND_PROFILES["coupon"] else 1.0
                )  # promo-code boosted welcome
                bonus_rows.append((i, ftd_s + 60, round(min(boost * ftd_amt, 150.0), 2), "welcome"))
        elif len(days) and rng.random() < 0.25:
            bonus_rows.append(
                (i, days[0] * DAY_S + 3600, round(min(50.0, 0.25 * month_dep), 2), "reload")
            )
        if one_and_done or rng.random() > prof.retention:
            break
        m += 1
    return last


def _crm_tables(rng, pid, ftd_s, last_active, start, obs_end, obs_end_s):
    n = len(pid)
    consents = pd.DataFrame(
        {
            "player_id": pid,
            "email": rng.random(n) < 0.72,
            "sms": rng.random(n) < 0.38,
            "push": rng.random(n) < 0.50,
        }
    )
    dep_idx = np.nonzero(~np.isnan(ftd_s))[0]
    se = dep_idx[rng.random(len(dep_idx)) < 0.015]
    se_start = np.minimum(last_active[se] + rng.uniform(0, 10, len(se)) * DAY_S, obs_end_s - DAY_S)
    permanent = rng.random(len(se)) < 0.4
    se_end = np.where(permanent, np.nan, se_start + 182 * DAY_S)
    co = dep_idx[rng.random(len(dep_idx)) < 0.02]
    co_start = obs_end_s - rng.uniform(0, 20, len(co)) * DAY_S
    ex = pd.DataFrame(
        {
            "player_id": np.concatenate([pid[se], pid[co]]),
            "exclusion_type": ["self_exclusion"] * len(se) + ["cool_off"] * len(co),
            "start_s": np.concatenate([se_start, co_start]),
            "end_s": np.concatenate([se_end, co_start + 30 * DAY_S]),
        }
    )
    exclusions = pd.DataFrame(
        {
            "player_id": ex["player_id"],
            "exclusion_type": ex["exclusion_type"],
            "start_ts": start + pd.to_timedelta(ex["start_s"].to_numpy(), unit="s").round("s"),
            "end_ts": start + pd.to_timedelta(ex["end_s"].to_numpy(), unit="s").round("s"),
        }
    )
    rows = []
    for ch, lam in (("email", 1.6), ("sms", 0.5), ("push", 2.2)):
        cnt = rng.poisson(lam, len(dep_idx))
        who = np.repeat(dep_idx, cnt)
        t = obs_end_s - rng.uniform(0, 14, len(who)) * DAY_S
        rows.append(pd.DataFrame({"player_id": pid[who], "channel": ch, "s": t}))
    s = pd.concat(rows, ignore_index=True)
    sends = pd.DataFrame(
        {
            "player_id": s["player_id"],
            "channel": s["channel"],
            "sent_ts": start + pd.to_timedelta(s["s"].to_numpy(), unit="s").round("s"),
            "campaign_id": "CMP_" + pd.Series(rng.integers(100, 140, len(s))).astype(str),
        }
    )
    return consents, exclusions, sends


def _partner_reports(rng, clicks, players, deposits, obs_end) -> pd.DataFrame:
    """Partner-side conversion claims (their own tracking, UTC+3 month cut, with noise)."""
    ftd = deposits[deposits["is_ftd"]][["player_id", "dep_ts", "amount"]]
    # map every click that belongs to a registered player (last and non-last clicks)
    pc = players[["player_id", "click_id", "reg_ts"]]
    last_clicks = clicks.merge(pc[["click_id", "player_id"]], on="click_id", how="inner")
    # earlier (non-last) clicks share device with the player: partner still claims them
    other = clicks[~clicks["click_id"].isin(pc["click_id"])].merge(
        players[["player_id", "device_fp", "reg_ts"]], on="device_fp", how="inner"
    )
    other = other[other["click_ts"] < other["reg_ts"]].drop(columns=["reg_ts"])
    cand = pd.concat([last_clicks, other], ignore_index=True).merge(ftd, on="player_id")
    rows = []
    last_full_month = (obs_end.to_period("M")).strftime("%Y-%m")
    for aff, grp in cand.groupby("affiliate_id"):
        contract = CONTRACTS[aff]
        if contract.cpa is None:
            continue
        g = grp.sort_values("click_ts").drop_duplicates("player_id", keep="last").copy()
        g["report_month"] = (g["dep_ts"] + pd.Timedelta(hours=3)).dt.to_period("M").astype(str)
        g = g[g["report_month"] <= last_full_month]
        keep = rng.random(len(g)) >= 0.02
        g = g[keep]
        g["claimed_commission"] = np.where(
            rng.random(len(g)) < 0.04, contract.cpa.amount + 20, contract.cpa.amount
        )
        dup = g[rng.random(len(g)) < 0.02]
        fab_share = 0.08 if aff in ("AFF08", "AFF09") else 0.02
        n_fab = int(round(len(g) * fab_share))
        fab = pd.DataFrame(
            {
                "click_id": [f"X{aff}{k:06d}" for k in range(n_fab)],
                "dep_ts": g["dep_ts"]
                .sample(n_fab, replace=True, random_state=int(rng.integers(1 << 30)))
                .to_numpy()
                if n_fab
                else [],
                "report_month": g["report_month"]
                .sample(n_fab, replace=True, random_state=int(rng.integers(1 << 30)))
                .to_numpy()
                if n_fab
                else [],
                "claimed_commission": contract.cpa.amount,
            }
        )
        out = pd.concat([g, dup, fab], ignore_index=True)
        out["affiliate_id"] = aff
        rows.append(
            out[["affiliate_id", "report_month", "click_id", "dep_ts", "claimed_commission"]]
        )
    rep = pd.concat(rows, ignore_index=True).rename(columns={"dep_ts": "claimed_ftd_ts"})
    rep = rep.sample(frac=1.0, random_state=int(rng.integers(1 << 30))).reset_index(drop=True)
    rep.insert(0, "claim_id", [f"CL{k:07d}" for k in range(len(rep))])
    return rep
