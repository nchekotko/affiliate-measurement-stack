"""Seeded generator of SYNTHETIC DEMO DATA for the affiliate measurement stack.

Nothing produced here is evidence about any real operator, affiliate or market.
The generator encodes known mechanisms (brand-bidding interception, coupon
last-click stealing, incentivised traffic, bot-farm bursts, bonus abuse) so the
analytics can be checked against a known ground truth.

Public tables mimic what an operator's tracking/back office would see.
Ground truth (fraud labels, true origin of each player, incrementality) is
returned separately and must only be used for evaluation.
"""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np
import pandas as pd

from .config import (
    AFFILIATES,
    BRAND_BIDDER,
    CONTRACTS,
    COUPON_AFFILIATE,
    KIND_PROFILES,
    SEO_AFFILIATES,
    AffiliateSpec,
    SimConfig,
)

SYNTHETIC_NOTICE = "SYNTHETIC DEMO DATA - generated by affmeasure.generator; not real market data"

DECLARED_TYPE = {
    "seo": "seo_content",
    "brand_bidding": "ppc_brand",
    "coupon": "coupon",
    "streamer": "streamer",
    "tipster": "tipster",
    "incentivised": "cashback_rewards",
    "bot_farm": "media_network",
    "media": "media_network",
}

DAY_S = 86_400.0


@dataclass
class SyntheticData:
    tables: dict[str, pd.DataFrame]
    ground_truth: dict[str, pd.DataFrame]
    config: SimConfig


# --------------------------------------------------------------------------- helpers


def _season(n_days: int, start: pd.Timestamp) -> np.ndarray:
    d = np.arange(n_days)
    week = d // 7
    dow = (start.dayofweek + d) % 7
    return (
        (1 + 0.004 * week)
        * (1 + 0.10 * np.sin(2 * np.pi * (d + 30) / 365))
        * np.where(dow >= 5, 1.15, 0.95)
    )


def _expand(counts: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    """counts[day, geo] -> arrays of (day, geo) with one row per unit."""
    flat = counts.ravel()
    idx = np.repeat(np.arange(flat.size), flat)
    return idx // counts.shape[1], idx % counts.shape[1]


def _geo_design(
    cfg: SimConfig, geo_w: np.ndarray, rng: np.random.Generator
) -> tuple[np.ndarray, pd.DataFrame]:
    G, W = cfg.n_geos, cfg.n_weeks
    n_early = round(G * cfg.did_early_geo_share)
    early = np.argsort(-geo_w)[:n_early]  # non-random: the biggest geos launch first
    holdout = rng.choice(G, round(G * cfg.holdout_share), replace=False)
    on = np.zeros((W, G), dtype=bool)
    on[cfg.did_launch_week : cfg.holdout_start_week, early] = True
    on[cfg.holdout_start_week : cfg.switchback_start_week, :] = True
    on[cfg.holdout_start_week : cfg.switchback_start_week, holdout] = False
    n_sw = W - cfg.switchback_start_week
    on[cfg.switchback_start_week :, :] = rng.random((n_sw, G)) < 0.5

    weeks = np.arange(W)
    phase = np.select(
        [
            weeks < cfg.did_launch_week,
            weeks < cfg.holdout_start_week,
            weeks < cfg.switchback_start_week,
        ],
        ["did_pre", "did_post", "holdout"],
        "switchback",
    )
    rows = []
    early_set, hold_set = set(early.tolist()), set(holdout.tolist())
    for w in weeks:
        for g in range(G):
            rows.append(
                (
                    f"G{g:02d}",
                    int(w),
                    bool(on[w, g]),
                    phase[w],
                    "early" if g in early_set else "late",
                    "holdout" if g in hold_set else "control",
                )
            )
    design = pd.DataFrame(
        rows, columns=["geo", "week", "bb_on", "phase", "did_group", "holdout_group"]
    )
    return on, design


# --------------------------------------------------------------------------- generator


def generate(cfg: SimConfig | None = None) -> SyntheticData:
    cfg = cfg or SimConfig()
    rng = np.random.default_rng(cfg.seed)
    start = pd.Timestamp(cfg.start)
    obs_end = pd.Timestamp(cfg.obs_end)
    obs_end_s = (obs_end - start).total_seconds()
    n_days = cfg.n_weeks * 7
    G = cfg.n_geos
    season = _season(n_days, start)
    geo_w = rng.lognormal(0, 0.6, G)
    geo_w /= geo_w.sum()
    on_wg, design = _geo_design(cfg, geo_w, rng)
    on_dg = on_wg[np.arange(n_days) // 7]  # days x geos

    # ---------------------------------------------------------------- registrations
    streams: list[dict[str, np.ndarray]] = []

    def add_stream(day, geo, source, kind, fraud, origin, burst=None):
        n = len(day)
        streams.append(
            {
                "day": np.asarray(day, dtype=np.int64),
                "geo": np.asarray(geo, dtype=np.int64),
                "source": np.full(n, source, dtype=object),
                "kind": np.full(n, kind, dtype=object)
                if isinstance(kind, str)
                else np.asarray(kind, dtype=object),
                "fraud": np.full(n, fraud, dtype=object)
                if isinstance(fraud, str)
                else np.asarray(fraud, dtype=object),
                "origin": np.full(n, origin, dtype=object)
                if isinstance(origin, str)
                else np.asarray(origin, dtype=object),
                "burst": np.full(n, -1, dtype=np.int64)
                if burst is None
                else np.asarray(burst, dtype=np.int64),
            }
        )

    lam_org = cfg.organic_daily * cfg.scale * season[:, None] * geo_w[None, :]
    n_org = rng.poisson(lam_org)
    brand = rng.binomial(n_org, cfg.brand_search_share)
    intercepted = rng.binomial(brand, np.where(on_dg, cfg.bb_intercept_rate, 0.0))
    incr = rng.poisson(
        lam_org * cfg.brand_search_share * cfg.bb_intercept_rate * cfg.bb_incremental_ratio * on_dg
    )
    d, g = _expand(n_org - intercepted)
    add_stream(d, g, "ORGANIC", "organic", "none", "organic")
    d, g = _expand(intercepted)
    add_stream(d, g, BRAND_BIDDER, "organic", "none", "bb_intercepted")
    d, g = _expand(incr)
    add_stream(d, g, BRAND_BIDDER, "brand_bidding", "none", "bb_incremental")

    burst_meta: list[tuple[int, int, float]] = []  # (burst_id -> day, geo, start offset)
    specs: dict[str, AffiliateSpec] = {a.affiliate_id: a for a in AFFILIATES}
    for spec in AFFILIATES:
        if spec.kind == "brand_bidding":
            continue
        w_a = geo_w * rng.lognormal(0, 0.3, G)
        w_a /= w_a.sum()
        lam = spec.daily_regs * cfg.scale * season[:, None] * w_a[None, :]
        d, g = _expand(rng.poisson(lam))
        fraud = np.where(rng.random(len(d)) < spec.fraud_share, spec.kind, "none")
        add_stream(d, g, spec.affiliate_id, spec.kind, fraud, "affiliate")
        if spec.bursts_per_day > 0:
            n_b = rng.poisson(spec.bursts_per_day * cfg.scale, n_days)
            bd, bg, bid = [], [], []
            for day in np.nonzero(n_b)[0]:
                for _ in range(n_b[day]):
                    size = int(rng.integers(5, 26))
                    geo = int(rng.choice(G, p=w_a))
                    b_id = len(burst_meta)
                    burst_meta.append((int(day), geo, float(rng.uniform(0, 0.97))))
                    bd += [day] * size
                    bg += [geo] * size
                    bid += [b_id] * size
            add_stream(bd, bg, spec.affiliate_id, spec.kind, "bot", "affiliate", bid)

    reg = pd.DataFrame({k: np.concatenate([s[k] for s in streams]) for k in streams[0]})
    n = len(reg)

    # coupon last-click stealing (organic and SEO users click a coupon site just before signing up)
    steal_org = (reg["origin"] == "organic") & (rng.random(n) < cfg.coupon_steal_organic)
    steal_seo = (
        reg["source"].isin(SEO_AFFILIATES)
        & (reg["fraud"] == "none")
        & (rng.random(n) < cfg.coupon_steal_seo)
    )
    reg["prior_source"] = np.where(steal_seo, reg["source"], None)
    reg.loc[steal_org, "origin"] = "coupon_steal_organic"
    reg.loc[steal_seo, "origin"] = "coupon_steal_seo"
    reg.loc[steal_org | steal_seo, "source"] = COUPON_AFFILIATE

    # bonus abuse (multi-accounting pairs) hidden among ordinary traffic
    abuse_pool = reg["kind"].isin(["organic", "seo", "coupon", "media", "tipster"]) & (
        reg["fraud"] == "none"
    )
    abuse = abuse_pool & (rng.random(n) < cfg.bonus_abuse_share)
    reg.loc[abuse, "fraud"] = "bonus_abuse"

    # registration timestamps (seconds from start)
    reg_s = (reg["day"].to_numpy() + rng.random(n)) * DAY_S
    is_burst = reg["burst"].to_numpy() >= 0
    if is_burst.any():
        b = reg["burst"].to_numpy()[is_burst]
        b_day = np.array([burst_meta[i][0] for i in b])
        b_off = np.array([burst_meta[i][2] for i in b])
        reg_s[is_burst] = (b_day + b_off) * DAY_S + rng.uniform(0, 480, is_burst.sum())
    reg["reg_s"] = reg_s
    reg = reg.sort_values("reg_s", kind="mergesort").reset_index(drop=True)
    n = len(reg)
    reg["player_id"] = [f"P{i:06d}" for i in range(1, n + 1)]
    reg_s = reg["reg_s"].to_numpy()
    fraud = reg["fraud"].to_numpy()
    source = reg["source"].to_numpy()

    # sub ids: fraud concentrated in a few subs
    sub = np.empty(n, dtype=object)
    for aff, spec in specs.items():
        m = source == aff
        if not m.any():
            continue
        k = spec.n_subs
        weights = 1 / np.arange(1, k + 1)
        weights /= weights.sum()
        choice = rng.choice(k, m.sum(), p=weights) + 1
        f = fraud[m]
        if spec.kind in ("incentivised", "bot_farm"):
            half = max(1, k // 2)
            choice = np.where(
                f != "none",
                rng.integers(1, half + 1, m.sum()),
                rng.integers(half + 1, k + 1, m.sum()),
            )
        sub[m] = [f"{aff}_s{c}" for c in choice]

    # device and payment fingerprints
    device = np.array([f"D{i:07d}" for i in range(n)], dtype=object)
    payfp = np.array([f"F{i:07d}" for i in range(n)], dtype=object)
    abuse_idx = np.nonzero(fraud == "bonus_abuse")[0]
    for a, b in zip(abuse_idx[0::2], abuse_idx[1::2], strict=False):
        device[b] = device[a]
        payfp[b] = payfp[a]
    inc_idx = np.nonzero(fraud == "incentivised")[0]
    if len(inc_idx):
        pool = max(1, len(inc_idx) // 5)
        shared = inc_idx[rng.random(len(inc_idx)) < 0.35]
        payfp[shared] = [f"FPOOL{p:05d}" for p in rng.integers(0, pool, len(shared))]
        dshared = inc_idx[rng.random(len(inc_idx)) < 0.15]
        device[dshared] = [
            f"DPOOL{p:05d}" for p in rng.integers(0, max(1, pool // 2), len(dshared))
        ]
    # benign collisions: households sharing a device, family cards
    legit_idx = np.nonzero(fraud == "none")[0]
    hh = legit_idx[rng.random(len(legit_idx)) < 0.015]
    device[hh] = device[rng.choice(legit_idx, len(hh))]
    fam = legit_idx[rng.random(len(legit_idx)) < 0.006]
    payfp[fam] = payfp[rng.choice(legit_idx, len(fam))]
    bot_idx = np.nonzero(fraud == "bot")[0]
    burst_arr = reg["burst"].to_numpy()
    for b_id in np.unique(burst_arr[bot_idx]) if len(bot_idx) else []:
        members = np.nonzero(burst_arr == b_id)[0]
        # some farms rotate device fingerprints (emulators), defeating the device rule
        n_dev = len(members) if rng.random() < 0.25 else max(1, len(members) // 5)
        device[members] = [f"DBOT{b_id:05d}_{k}" for k in rng.integers(0, n_dev, len(members))]
        payfp[members] = [f"FBOT{b_id:05d}_{k}" for k in np.arange(len(members)) // 2]

    # ---------------------------------------------------------------- clicks & touchpoints
    kinds = reg["kind"].to_numpy()
    origin = reg["origin"].to_numpy()
    has_aff = source != "ORGANIC"
    delay = rng.lognormal(np.log(240), 1.0, n) + 15
    fast_legit = rng.random(n) < 0.003
    delay = np.where(fast_legit, rng.uniform(3, 9, n), delay)
    delay = np.where(fraud == "bot", rng.uniform(1, 6, n), delay)
    click_s = reg_s - delay
    click_ids = np.array([f"C{i:08d}" for i in range(n)], dtype=object)
    geo_codes = np.array([f"G{g:02d}" for g in range(G)], dtype=object)
    reg_geo = geo_codes[reg["geo"].to_numpy()]

    clicks = [
        pd.DataFrame(
            {
                "click_id": click_ids[has_aff],
                "affiliate_id": source[has_aff],
                "sub_id": sub[has_aff],
                "click_s": click_s[has_aff],
                "geo": reg_geo[has_aff],
                "device_fp": device[has_aff],
                "player_idx": np.nonzero(has_aff)[0],
            }
        )
    ]
    # earlier SEO clicks for coupon-stolen SEO users
    seo_prior = np.nonzero(reg["prior_source"].notna().to_numpy())[0]
    if len(seo_prior):
        prior_aff = reg["prior_source"].to_numpy()[seo_prior]
        clicks.append(
            pd.DataFrame(
                {
                    "click_id": [f"C{n + i:08d}" for i in range(len(seo_prior))],
                    "affiliate_id": prior_aff,
                    "sub_id": [f"{a}_s1" for a in prior_aff],
                    "click_s": reg_s[seo_prior]
                    - delay[seo_prior]
                    - rng.uniform(3600, 5 * DAY_S, len(seo_prior)),
                    "geo": reg_geo[seo_prior],
                    "device_fp": device[seo_prior],
                    "player_idx": seo_prior,
                }
            )
        )
    next_click = n + len(seo_prior)

    # non-converting clicks
    for aff, spec in specs.items():
        n_regs = int((source == aff).sum())
        cr = KIND_PROFILES[spec.kind].click_to_reg
        extra = int(round(n_regs * (1 / cr - 1)))
        if extra <= 0:
            continue
        subs = rng.integers(1, spec.n_subs + 1, extra)
        clicks.append(
            pd.DataFrame(
                {
                    "click_id": [f"C{next_click + i:08d}" for i in range(extra)],
                    "affiliate_id": aff,
                    "sub_id": [f"{aff}_s{s}" for s in subs],
                    "click_s": rng.uniform(0, n_days * DAY_S, extra),
                    "geo": geo_codes[rng.choice(G, extra, p=geo_w)],
                    "device_fp": [f"V{next_click + i:08d}" for i in range(extra)],
                    "player_idx": -1,
                }
            )
        )
        next_click += extra
    clicks_df = pd.concat(clicks, ignore_index=True)

    tp_rows = []
    org_mask = source == "ORGANIC"
    tp_rows.append(
        pd.DataFrame(
            {
                "player_idx": np.nonzero(org_mask)[0],
                "touch_s": reg_s[org_mask] - rng.uniform(30, 1800, org_mask.sum()),
                "channel": np.where(rng.random(org_mask.sum()) < 0.6, "organic_search", "direct"),
            }
        )
    )
    brand_prior = np.isin(origin, ["bb_intercepted", "coupon_steal_organic"])
    tp_rows.append(
        pd.DataFrame(
            {
                "player_idx": np.nonzero(brand_prior)[0],
                "touch_s": reg_s[brand_prior]
                - delay[brand_prior]
                - rng.uniform(60, 7 * DAY_S, brand_prior.sum()),
                "channel": "organic_brand_search",
            }
        )
    )
    baseline = has_aff & ~brand_prior & (rng.random(n) < 0.06)
    tp_rows.append(
        pd.DataFrame(
            {
                "player_idx": np.nonzero(baseline)[0],
                "touch_s": reg_s[baseline] - rng.uniform(DAY_S, 30 * DAY_S, baseline.sum()),
                "channel": np.where(
                    rng.random(baseline.sum()) < 0.5, "organic_brand_search", "direct"
                ),
            }
        )
    )
    touch_df = pd.concat(tp_rows, ignore_index=True)

    # ---------------------------------------------------------------- lifecycle
    games = _games(rng)
    casino_games = games[games["vertical"] == "casino"]["game_id"].to_numpy()
    casino_pop = 1 / np.arange(1, len(casino_games) + 1) ** 0.8
    casino_pop /= casino_pop.sum()
    sports_games = games[games["vertical"] == "sports"]["game_id"].to_numpy()

    kyc_rows: list[tuple] = []
    dep_rows: list[tuple] = []
    bet_rows: list[tuple] = []
    wd_rows: list[tuple] = []
    cb_rows: list[tuple] = []
    bonus_rows: list[tuple] = []
    last_active = np.full(n, np.nan)
    ftd_s_arr = np.full(n, np.nan)
    method_of = rng.choice(["card", "ewallet", "open_banking"], n, p=[0.6, 0.25, 0.15])
    wd_bursts: dict[int, float] = {}

    for i in range(n):
        f = fraud[i]
        prof = KIND_PROFILES[kinds[i]]
        r0 = reg_s[i]
        if f == "none":
            if rng.random() < 0.93:
                passed = rng.random() < prof.kyc_rate / 0.93
                kyc_rows.append(
                    (i, r0 + rng.exponential(0.75 * DAY_S), "passed" if passed else "failed")
                )
            if rng.random() >= prof.ftd_rate:
                continue
            ftd_s = r0 + (
                rng.uniform(300, 3 * 3600) if rng.random() < 0.55 else rng.exponential(4 * DAY_S)
            )
            if ftd_s > obs_end_s:
                continue
            ftd_s_arr[i] = ftd_s
            last_active[i] = _legit_life(
                i,
                ftd_s,
                prof,
                rng,
                obs_end_s,
                method_of[i],
                payfp[i],
                casino_games,
                casino_pop,
                sports_games,
                dep_rows,
                bet_rows,
                wd_rows,
                cb_rows,
                bonus_rows,
            )
            continue
        # ---- fraudulent lifecycles
        if f == "incentivised":
            kyc_p, ftd_p, ftd_delay = 0.9, 0.92, rng.uniform(300, 7200)
            amount, promo, stake_tot, cb_p = (
                round(rng.uniform(20, 24), 2),
                10.0,
                rng.uniform(50, 62),
                0.01,
            )
            if rng.random() < 0.5:
                promo = 0.0  # no extra task bonus
            wd_s = None
            evasive = rng.random() < 0.25  # instructed to look like a normal player
        elif f == "bot":
            kyc_p, ftd_p, ftd_delay = 0.5, 0.85, rng.uniform(60, 1200)
            amount, promo, stake_tot, cb_p = (
                round(rng.uniform(20, 22), 2),
                15.0,
                rng.uniform(50, 58),
                0.4,
            )
            evasive = False
            b_id = int(burst_arr[i])
            if b_id not in wd_bursts:
                bday, _, boff = burst_meta[b_id]
                wd_bursts[b_id] = (bday + boff + 2) * DAY_S + rng.uniform(0, 12) * 3600
            wd_s = wd_bursts[b_id] + rng.uniform(0, 1500)
        else:  # bonus_abuse
            kyc_p, ftd_p, ftd_delay = 0.9, 0.9, rng.uniform(300, 6 * 3600)
            amount = round(rng.uniform(20, 40), 2)
            promo, stake_tot, cb_p = 0.8 * amount, amount * rng.uniform(2, 3), 0.02
            wd_s = None
            evasive = False
        if rng.random() < kyc_p:
            kyc_rows.append((i, r0 + rng.uniform(300, 6 * 3600), "passed"))
        else:
            kyc_rows.append((i, r0 + rng.uniform(300, 6 * 3600), "failed"))
        if rng.random() >= ftd_p:
            continue
        ftd_s = r0 + ftd_delay
        if ftd_s > obs_end_s:
            continue
        ftd_s_arr[i] = ftd_s
        dep_rows.append((i, ftd_s, amount, "card", payfp[i], True))
        bonus_rows.append((i, ftd_s + 60, amount, "welcome"))
        if promo > 0:
            bonus_rows.append((i, ftd_s + 120, promo, "promo"))
        pair = casino_games[rng.choice(10, 2, replace=False)]
        day0 = np.floor(ftd_s / DAY_S)
        n_days_bet = 1 if f != "bonus_abuse" else int(rng.integers(1, 4))
        if evasive:
            n_days_bet, stake_tot = 2, rng.uniform(70, 110)
        split = rng.dirichlet(np.ones(n_days_bet)) * stake_tot
        for k in range(n_days_bet):
            game = pair[k % 2] if evasive else pair[0]
            stake = float(split[k])
            ggr = stake * 0.03 + rng.normal(0, 0.1 * stake)
            bet_rows.append((i, day0 + k, game, int(stake // 1) + 1, stake, min(ggr, amount)))
        if wd_s is None:
            wd_s = ftd_s + rng.uniform(1, 3) * DAY_S
        wd_rows.append((i, wd_s, round(amount * rng.uniform(0.7, 1.1), 2)))
        if rng.random() < cb_p:
            cb_rows.append((i, len(dep_rows) - 1, ftd_s + rng.uniform(20, 60) * DAY_S, amount))
        last_active[i] = wd_s

    # ---------------------------------------------------------------- assemble public tables
    pid = reg["player_id"].to_numpy()

    def ts(sec) -> pd.Series:
        return start + pd.to_timedelta(np.asarray(sec, dtype=float), unit="s").round("s")

    players = pd.DataFrame(
        {
            "player_id": pid,
            "reg_ts": ts(reg_s),
            "geo": reg_geo,
            "click_id": np.where(has_aff, click_ids, None),
            "device_fp": device,
        }
    )
    clicks_df = clicks_df.assign(click_ts=ts(clicks_df["click_s"]))
    clicks_df = clicks_df[["click_id", "affiliate_id", "sub_id", "click_ts", "geo", "device_fp"]]
    touch = pd.DataFrame(
        {
            "player_id": pid[touch_df["player_idx"]],
            "touch_ts": ts(touch_df["touch_s"]),
            "channel": touch_df["channel"],
        }
    )
    kyc = pd.DataFrame(kyc_rows, columns=["i", "s", "status"])
    kyc = pd.DataFrame(
        {"player_id": pid[kyc["i"]], "kyc_ts": ts(kyc["s"]), "status": kyc["status"]}
    )

    dep = pd.DataFrame(dep_rows, columns=["i", "s", "amount", "method", "payment_fp", "is_ftd"])
    dep["deposit_id"] = [f"DEP{k:08d}" for k in range(len(dep))]
    cb = pd.DataFrame(cb_rows, columns=["i", "dep_row", "s", "amount"])
    cb = cb[cb["s"] <= obs_end_s]
    chargebacks = pd.DataFrame(
        {
            "player_id": pid[cb["i"]],
            "deposit_id": dep["deposit_id"].to_numpy()[cb["dep_row"].to_numpy(dtype=int)],
            "cb_ts": ts(cb["s"]),
            "amount": cb["amount"].round(2),
        }
    )
    dep = dep[dep["s"] <= obs_end_s]
    deposits = pd.DataFrame(
        {
            "deposit_id": dep["deposit_id"],
            "player_id": pid[dep["i"]],
            "dep_ts": ts(dep["s"]),
            "amount": dep["amount"].round(2),
            "method": dep["method"],
            "payment_fp": dep["payment_fp"],
            "is_ftd": dep["is_ftd"],
        }
    )
    bets = pd.DataFrame(bet_rows, columns=["i", "day", "game_id", "n_bets", "stake", "ggr"])
    bets = bets[bets["day"] * DAY_S <= obs_end_s]
    bets = pd.DataFrame(
        {
            "player_id": pid[bets["i"]],
            "bet_date": (start + pd.to_timedelta(bets["day"], unit="D")).dt.normalize(),
            "game_id": bets["game_id"],
            "n_bets": bets["n_bets"].astype(int),
            "stake": bets["stake"].round(2),
            "ggr": bets["ggr"].round(2),
        }
    )
    wd = pd.DataFrame(wd_rows, columns=["i", "s", "amount"])
    wd = wd[wd["s"] <= obs_end_s]
    withdrawals = pd.DataFrame(
        {
            "withdrawal_id": [f"WD{k:08d}" for k in range(len(wd))],
            "player_id": pid[wd["i"]],
            "wd_ts": ts(wd["s"]),
            "amount": wd["amount"].round(2),
        }
    )
    bn = pd.DataFrame(bonus_rows, columns=["i", "s", "amount", "bonus_type"])
    bn = bn[bn["s"] <= obs_end_s]
    bonuses = pd.DataFrame(
        {
            "player_id": pid[bn["i"]],
            "bonus_ts": ts(bn["s"]),
            "amount": bn["amount"].round(2),
            "bonus_type": bn["bonus_type"],
        }
    )

    affiliates = pd.DataFrame(
        {
            "affiliate_id": [a.affiliate_id for a in AFFILIATES],
            "name": [a.name for a in AFFILIATES],
            "declared_type": [DECLARED_TYPE[a.kind] for a in AFFILIATES],
            "contract": [CONTRACTS[a.affiliate_id].kind for a in AFFILIATES],
        }
    )

    consents, exclusions, sends = _crm_tables(
        rng, pid, ftd_s_arr, last_active, start, obs_end, obs_end_s
    )
    partner = _partner_reports(rng, clicks_df, players, deposits, obs_end)

    tables = {
        "affiliates": affiliates,
        "geo_design": design,
        "clicks": clicks_df.reset_index(drop=True),
        "touchpoints": touch,
        "players": players,
        "kyc": kyc,
        "deposits": deposits.reset_index(drop=True),
        "bets": bets.reset_index(drop=True),
        "games": games,
        "withdrawals": withdrawals,
        "chargebacks": chargebacks.reset_index(drop=True),
        "bonuses": bonuses.reset_index(drop=True),
        "crm_consents": consents,
        "self_exclusions": exclusions,
        "crm_sends": sends,
        "partner_reports": partner,
    }
    truth = pd.DataFrame(
        {
            "player_id": pid,
            "fraud_type": fraud,
            "is_fraud": fraud != "none",
            "origin": origin,
            "true_kind": kinds,
        }
    )
    return SyntheticData(tables=tables, ground_truth={"player_truth": truth}, config=cfg)


